import { describe, expect, it } from 'vitest';
import ExcelJS from 'exceljs';
import { parseWorkbookFile } from '../utils/excelCleaner';

describe('parseWorkbookFile', () => {
  it('parses quoted CSV delimiters, escaped quotes, and embedded line breaks', async () => {
    const csv = [
      'itemname;description;price',
      'Widget;"line one',
      'line ""two""";12,50',
    ].join('\r\n');
    const result = await parseWorkbookFile(new TextEncoder().encode(csv), 'items.csv');

    expect(result.headers).toEqual(['itemname', 'description', 'price']);
    expect(result.rows).toEqual([['Widget', 'line one\r\nline "two"', '12,50']]);
    expect(result.worksheetNames).toEqual([]);
  });

  it('rejects malformed or unfinished quoted CSV fields', async () => {
    await expect(parseWorkbookFile(
      new TextEncoder().encode('itemname,price\n"Widget,12.50'),
      'items.csv'
    )).rejects.toThrow('champ entre guillemets non terminé');
    await expect(parseWorkbookFile(
      new TextEncoder().encode('itemname,price\nWi"dget,12.50'),
      'items.csv'
    )).rejects.toThrow('guillemet non échappé');
  });

  it('lists workbook worksheets and allows a caller to select a non-first sheet', async () => {
    const workbook = new ExcelJS.Workbook();
    workbook.addWorksheet('Cover').addRow(['Report generated by E-Studio']);
    const dataSheet = workbook.addWorksheet('Products');
    dataSheet.addRow(['itemname', 'price']);
    dataSheet.addRow(['Widget', 12.5]);
    const bytes = new Uint8Array(await workbook.xlsx.writeBuffer());

    const first = await parseWorkbookFile(bytes, 'products.xlsx');
    const selected = await parseWorkbookFile(bytes, 'products.xlsx', 'Products');

    expect(first.worksheetNames).toEqual(['Cover', 'Products']);
    expect(selected.headers).toEqual(['itemname', 'price']);
    expect(selected.rows).toEqual([['Widget', 12.5]]);
  });

  it('fails explicitly if a requested worksheet does not exist', async () => {
    const workbook = new ExcelJS.Workbook();
    workbook.addWorksheet('Products').addRow(['itemname', 'price']);
    const bytes = new Uint8Array(await workbook.xlsx.writeBuffer());

    await expect(parseWorkbookFile(bytes, 'products.xlsx', 'Missing'))
      .rejects.toThrow('La feuille Excel "Missing" est introuvable.');
  });

  it('reports legacy XLS as unsupported instead of misreading it as an XLSX archive', async () => {
    await expect(parseWorkbookFile(new Uint8Array([0, 1, 2]), 'legacy.xls'))
      .rejects.toThrow('Le format Excel .xls ancien n’est pas pris en charge.');
  });
});
