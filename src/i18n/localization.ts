export function isSupportedLocale(value: string): value is Locale {
  return (SUPPORTED_LOCALES as readonly string[]).includes(value);
}

export function getInitialLocale(storedLocale: string | null, browserLocale: string): Locale {
  if (storedLocale && isSupportedLocale(storedLocale)) return storedLocale;
  const normalized = browserLocale.replace('_', '-');
  if (isSupportedLocale(normalized)) return normalized;
  const base = normalized.split('-')[0];
  return isSupportedLocale(base) ? base : 'en';
}

export function getTranslationLocale(locale: Locale): Locale {
  return locale;
}

export function isRightToLeftLocale(locale: Locale): boolean {
  return locale === 'ar' || locale === 'he';
}

export function translate(locale: Locale, key: MessageKey): string {
  const selectedLocale = getTranslationLocale(locale);
  return extraMessages[selectedLocale][key] ?? messages[selectedLocale][key] ?? messages.en[key] ?? key;
}

export function translateDatabaseImport(locale: Locale, key: DatabaseImportKey): string {
  return databaseImportMessages[locale][key];
}

export function translateAccessibility(locale: Locale, key: AccessibilityKey): string {
  return accessibilityMessages[locale][key];
}

export function translateDashboardAction(locale: Locale, key: DashboardActionKey): string {
  return dashboardActionMessages[locale][key];
}

export function translateTemplateWizard(locale: Locale, key: TemplateWizardKey): string {
  return templateWizardMessages[locale][key];
}

